/**
 * Generates one static route file per page and language from lib/routes.ts.
 * Static folders (instead of a catch-all) let unknown URLs fall through to
 * app/global-not-found.tsx, which is server-rendered with HTTP 404.
 *
 *   npx tsx scripts/generate-routes.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import { LANGS, PAGE_KEYS, route } from '../lib/routes';

const root = path.resolve(__dirname, '..', 'app');
for (const lang of LANGS) {
  const base = lang === 'uz' ? path.join(root, '(uz)') : path.join(root, '(ru)', 'ru');
  for (const key of PAGE_KEYS) {
    const p = route(key).path;
    const dir = p === '/' ? base : path.join(base, ...p.slice(1).split('/'));
    fs.mkdirSync(dir, { recursive: true });
    const src = `// Generated by scripts/generate-routes.ts — do not edit by hand.
import { PageView } from '@/components/PageView';
import { pageMetadata } from '@/lib/metadata';

export const metadata = pageMetadata('${key}', '${lang}');

export default function Page() {
  return <PageView k="${key}" lang="${lang}" />;
}
`;
    fs.writeFileSync(path.join(dir, 'page.tsx'), src);
  }
}
console.log(`Generated ${PAGE_KEYS.length * LANGS.length} route files.`);
